#!/usr/bin/env node
/**
 * Generate lib/forage-find/evt-names.ts: LANDFIRE 2023 Existing Vegetation Type (EVT) code → name,
 * lifeform, physiognomy, group and SAF/SRM cover type, for the codes that can occur in California /
 * Nevada (and the West generally). Forage Finder looks up the GRAY_INDEX returned by the LANDFIRE
 * WMS GetFeatureInfo call in this table to describe tree cover at a candidate spot.
 *
 * Input: LANDFIRE's published attribute table LF23_EVT_240.csv
 *   https://landfire.gov/sites/default/files/CSV/LF2023/LF23_EVT_240.csv
 * cached at .cache/landfire/LF23_EVT_240.csv (gitignored; downloaded when missing).
 *
 *   node scripts/build-evt-names.mjs
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC_URL = "https://landfire.gov/sites/default/files/CSV/LF2023/LF23_EVT_240.csv";
const CACHE = path.join(ROOT, ".cache/landfire/LF23_EVT_240.csv");
const OUT = path.join(ROOT, "lib/forage-find/evt-names.ts");

/** Quoted-field-aware CSV line splitter (LANDFIRE quotes names that contain commas). */
export function splitCsvLine(line) {
  const out = [];
  let cur = "";
  let q = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (q) {
      if (c === '"' && line[i + 1] === '"') {
        cur += '"';
        i++;
      } else if (c === '"') q = false;
      else cur += c;
    } else if (c === '"') q = true;
    else if (c === ",") {
      out.push(cur);
      cur = "";
    } else cur += c;
  }
  out.push(cur);
  return out;
}

/**
 * Systems that don't occur in CA/NV. LANDFIRE codes 7000-9999 are CONUS; within those, these
 * name fragments mark eastern / Great Plains / Gulf / Southwest-only ecological systems.
 */
const NOT_CA_NV =
  /Alaska|Hawai|Laurentian|Appalach|Atlantic|Gulf|Florida|Great Plains|Ozark|Ouachita|Central Interior|Coastal Plain|Piedmont|Caribbean|Acadian|Boreal|Northeastern|Southeastern|Edwards Plateau|Tamaulipan|Texas|Mississipp|Prairie|Allegheny|Cumberland|Great Lakes|Bluegrass|Nashville|Carolina|Interior Low Plateau|Cross ?[Tt]imbers|Llano|Eastern|Southern Piedmont|Central Appalachian|Chihuahuan|Madrean|Apacherian|Western Great Plains|North-Central|Midwest|Lower Midwest|Upper Midwest|Southern Ridge|Coahuilan|Northern Atlantic|Glaciated|Crowley|Blackland|Central Mixedgrass|Central Tallgrass|Southern Blue Ridge|Oak Openings|Paleozoic|Cumberland/;

export function keepCode(value, name, group = "") {
  return value >= 7000 && value <= 9999 && !NOT_CA_NV.test(name) && !NOT_CA_NV.test(group);
}

function tidy(s) {
  return (s ?? "").trim().replace(/\s+/g, " ");
}

export function parseEvtCsv(text) {
  const lines = text.split(/\r?\n/).filter(Boolean);
  const head = splitCsvLine(lines[0]);
  const col = (n) => {
    const i = head.indexOf(n);
    if (i < 0) throw new Error(`EVT CSV is missing column ${n}`);
    return i;
  };
  const iV = col("VALUE"), iN = col("EVT_NAME"), iLf = col("EVT_LF"), iPh = col("EVT_PHYS"), iGp = col("EVT_GP_N"), iSaf = col("SAF_SRM");
  const rows = [];
  for (const line of lines.slice(1)) {
    const f = splitCsvLine(line);
    const value = Number(f[iV]);
    const name = tidy(f[iN]);
    if (!Number.isInteger(value) || !name) continue;
    if (!keepCode(value, name, f[iGp])) continue;
    const na = (s) => (s && s !== "NA" ? tidy(s) : "");
    rows.push({ code: value, name, lf: na(f[iLf]), phys: na(f[iPh]), group: na(f[iGp]), saf: na(f[iSaf]).replace(/^(SAF|SRM|LF) \d+:\s*/, "") });
  }
  return rows.sort((a, b) => a.code - b.code);
}

async function main() {
  if (!existsSync(CACHE)) {
    mkdirSync(path.dirname(CACHE), { recursive: true });
    console.log(`downloading ${SRC_URL}`);
    const res = await fetch(SRC_URL);
    if (!res.ok) throw new Error(`HTTP ${res.status} for ${SRC_URL}`);
    writeFileSync(CACHE, await res.text());
  }
  const rows = parseEvtCsv(readFileSync(CACHE, "utf8"));
  const body = rows
    .map((r) => `  ${r.code}: ${JSON.stringify([r.name, r.lf, r.phys, r.group, r.saf])},`)
    .join("\n");
  const out = `// AUTO-GENERATED by scripts/build-evt-names.mjs from LANDFIRE LF23_EVT_240.csv. Do not edit by hand.
// ${rows.length} LANDFIRE 2023 Existing Vegetation Type codes that can occur in California / Nevada
// (CONUS codes 7000-9999 minus eastern / plains / Gulf / desert-southwest-only systems).
// Source: ${SRC_URL}

/** [EVT_NAME, EVT_LF lifeform, EVT_PHYS physiognomy, EVT_GP_N group, SAF/SRM cover type] */
export type EvtRow = [name: string, lifeform: string, physiognomy: string, group: string, coverType: string];

export const EVT_NAMES: Record<number, EvtRow> = {
${body}
};
`;
  mkdirSync(path.dirname(OUT), { recursive: true });
  writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${rows.length} codes)`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
