// Imports Keeper's CA/NV fishing-regulation data into Foray as committed, offline-ready files.
//
//   KEEPER_DIR=... node --experimental-strip-types scripts/import-keeper.mjs [--out <dir>]
//
// Reads data/{corridor,california,nevada}/*.json, validates with Keeper's own zod schemas (via
// Keeper's tsx, see scripts/lib/keeper-validate.mts) and writes, under --out (default: repo root):
//   lib/fishing/engine/*.ts        verbatim copy of Keeper's DB-free src/resolve
//   lib/fishing/waters-index.ts    FISH_WATERS summaries (no rules)
//   lib/fishing/meta.ts            FISHING_DATA
//   public/fishing/w/<slug>.json   one WaterDataset per water
//   public/fishing/stocking-recent.json
//   scripts/fixtures/keeper-goldens.json
// Candidate-building mirrors Keeper's src/ingest/load.ts + src/api/rules.ts.
import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const keeperDir = resolve(process.env.KEEPER_DIR ?? join(homedir(), "projects/keeper/.claude/worktrees/pure-resolve"));
const outArg = process.argv.indexOf("--out");
const out = outArg > -1 ? resolve(process.argv[outArg + 1]) : repoRoot;
const BANNER = "// GENERATED by scripts/import-keeper.mjs — do not edit by hand";

if (!existsSync(join(keeperDir, "src/resolve"))) throw new Error(`KEEPER_DIR not found or not a Keeper checkout: ${keeperDir}`);
const git = (...a) => execFileSync("git", ["-C", keeperDir, ...a], { encoding: "utf8" }).trim();
const keeperSha = git("rev-parse", "HEAD");
const exportedAt = git("log", "-1", "--format=%cI"); // deterministic: Keeper HEAD commit date

// --- validate with Keeper's own schemas -----------------------------------------------------
const validation = JSON.parse(execFileSync(
  join(keeperDir, "node_modules/.bin/tsx"),
  [join(repoRoot, "scripts/lib/keeper-validate.mts"), keeperDir],
  { cwd: keeperDir, encoding: "utf8", maxBuffer: 256 * 1024 * 1024 },
)).files;

// --- load datasets (dir/file order, same as Keeper's ingest) --------------------------------
const dataRoot = join(keeperDir, "data");
const dirs = readdirSync(dataRoot).filter((f) => statSync(join(dataRoot, f)).isDirectory()).sort();
const entries = dirs.flatMap((dir) => readdirSync(join(dataRoot, dir)).filter((f) => f.endsWith(".json")).sort().map((f) => {
  const v = validation[`${dir}/${f}`];
  if (!v || v.error) throw new Error(`${dir}/${f}: ${v?.error ?? "not validated"}`);
  return { dir, base: f.slice(0, -5), ds: JSON.parse(readFileSync(join(dataRoot, dir, f), "utf8")), params: v.params };
}));

// Slugs that appear in more than one data dir get "<slug>-<dir>" everywhere; others stay as-is.
const baseCount = new Map();
for (const e of entries) baseCount.set(e.base, (baseCount.get(e.base) ?? 0) + 1);
for (const e of entries) e.slug = baseCount.get(e.base) > 1 ? `${e.base}-${e.dir}` : e.base;

// --- candidate rules ------------------------------------------------------------------------
let nextRegId = 0;
let excluded = 0;
const territoryByAuthority = new Map(); // authority name -> CandidateRule[] (authority_territory rules)
for (const e of entries) {
  const authName = new Map(e.ds.authorities.map((a) => [a.key, a.name]));
  const groupById = new Map(e.ds.groups.map((g) => [g.key, g]));
  const periodByKey = new Map(e.ds.seasonPeriods.map((p) => [p.key, p]));
  const sourceByKey = new Map(e.ds.sources.map((s) => [s.key, s]));
  const speciesGroupByKey = new Map(e.ds.speciesGroups.map((g) => [g.key, g]));
  e.own = [];
  e.ds.regulations.forEach((r, i) => {
    const regId = nextRegId++;
    const parameters = e.params[i];
    if (parameters === null || parameters === undefined) { excluded++; return; } // failed Keeper's validators
    const sp = r.seasonPeriodKey ? periodByKey.get(r.seasonPeriodKey) : null;
    const labels = r.speciesTargets.map((t) => ("speciesGroupKey" in t ? speciesGroupByKey.get(t.speciesGroupKey).name : t.speciesCommonName));
    const cand = {
      regId,
      ruleType: r.ruleType,
      parameters,
      polarity: r.rulePolarity,
      confidence: r.confidence,
      appliesTo: r.appliesToClass,
      citation: r.citation ?? (r.groupKey ? groupById.get(r.groupKey)?.citation : null) ?? null,
      summary: r.humanSummary,
      sourceUrl: sourceByKey.get(r.sourceKeys.primary)?.url ?? null,
      species: labels,
      scopeKey: r.scope.type === "reach" ? `reach:${r.scope.reachKey}` : "water",
      period: sp ? { status: sp.status, start: sp.startSpec, end: sp.endSpec } : null,
      validFrom: null,
      validTo: null,
      authorityName: authName.get(r.authorityKey),
    };
    if (r.scope.type === "authority_territory") {
      const name = authName.get(r.scope.authorityKey);
      if (!territoryByAuthority.has(name)) territoryByAuthority.set(name, []);
      territoryByAuthority.get(name).push(cand);
    } else {
      e.own.push(cand);
    }
  });
}

// --- per-water datasets ---------------------------------------------------------------------
const datasets = entries.map((e) => {
  const { ds } = e;
  const authNames = new Set(ds.authorities.map((a) => a.name));
  const territory = [...authNames].flatMap((n) => territoryByAuthority.get(n) ?? []);
  const candidates = [...e.own, ...territory].sort((a, b) => a.regId - b.regId);
  const authName = new Map(ds.authorities.map((a) => [a.key, a.name]));
  const srcUrl = new Map(ds.sources.map((s) => [s.key, s.url]));
  const summary = {
    slug: e.slug, name: ds.water.name, waterType: ds.water.waterType, states: ds.water.states,
    lon: ds.water.lon, lat: ds.water.lat, verifyCurrent: ds.water.verifyCurrent,
    species: ds.species.map((s) => s.commonName),
  };
  const events = (ds.stockingEvents ?? []).map((x, i) => ({ x, i }))
    .sort((a, b) => (a.x.date < b.x.date ? 1 : a.x.date > b.x.date ? -1 : a.i - b.i))
    .map(({ x }) => ({ species: x.speciesCommonName, quantity: x.quantity, sizeNote: x.sizeNote, date: x.date, sourceUrl: srcUrl.get(x.sourceKeys.primary) ?? null }));
  return {
    summary,
    dataset: {
      slug: e.slug,
      asOf: ds.asOf,
      water: { ...summary, counties: ds.water.counties },
      candidates,
      reaches: ds.reaches.map((r) => ({ key: r.key, name: r.name, fromDesc: r.fromDesc, toDesc: r.toDesc, lon: r.lon, lat: r.lat, line: r.line ?? null })),
      reciprocity: ds.reciprocity.map((x) => ({
        honoringAuthority: authName.get(x.honoringAuthorityKey), honoredAuthority: x.honoredAuthorityKey ? (authName.get(x.honoredAuthorityKey) ?? null) : null,
        honored: x.honored, replacesStateLicense: x.replacesStateLicense, condition: x.condition,
      })),
      species: ds.species.map((s) => ({ commonName: s.commonName, scientificName: s.scientificName, category: s.category, presence: s.presence })),
      stocking: {
        events,
        schedule: (ds.stockingSchedule ?? []).map((x) => ({
          species: x.speciesCommonName, frequency: x.frequency, seasonStartMonth: x.seasonStartMonth, seasonEndMonth: x.seasonEndMonth,
          note: x.note, sourceUrl: srcUrl.get(x.sourceKeys.primary) ?? null,
        })),
      },
    },
  };
});

// --- write ----------------------------------------------------------------------------------
const sortKeys = (v) => Array.isArray(v) ? v.map(sortKeys)
  : v && typeof v === "object" ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, sortKeys(v[k])])) : v;
const json = (v) => JSON.stringify(sortKeys(v)) + "\n";
const put = (rel, data) => { const p = join(out, rel); mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, data); };

// engine: verbatim copy
const engineOut = join(out, "lib/fishing/engine");
rmSync(engineOut, { recursive: true, force: true });
mkdirSync(engineOut, { recursive: true });
for (const f of readdirSync(join(keeperDir, "src/resolve")).filter((n) => n.endsWith(".ts")).sort()) {
  copyFileSync(join(keeperDir, "src/resolve", f), join(engineOut, f));
}

// water datasets
const wOut = join(out, "public/fishing/w");
rmSync(wOut, { recursive: true, force: true });
for (const d of datasets) put(`public/fishing/w/${d.summary.slug}.json`, json(d.dataset));

// index (sorted by slug; one object per line)
const index = datasets.map((d) => d.summary).sort((a, b) => (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0));
put("lib/fishing/waters-index.ts", [
  BANNER,
  'import type { WaterSummary } from "./types.ts";',
  "",
  "export const FISH_WATERS: WaterSummary[] = [",
  ...index.map((s) => `  ${JSON.stringify(sortKeys(s))},`),
  "];",
  "",
].join("\n"));

put("lib/fishing/meta.ts", [
  BANNER,
  "export const FISHING_DATA = {",
  `  keeperSha: ${JSON.stringify(keeperSha)},`,
  `  exportedAt: ${JSON.stringify(exportedAt)},`,
  `  waterCount: ${index.length},`,
  "};",
  "",
].join("\n"));

// every stocking event, newest first
const recent = datasets.flatMap((d) => d.dataset.stocking.events.map((ev) => ({ ...ev, slug: d.summary.slug, waterName: d.summary.name })))
  .sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : a.species < b.species ? -1 : a.species > b.species ? 1 : 0));
put("public/fishing/stocking-recent.json", json(recent));

// goldens fixture: translate "slug@dir" keys to the Foray slug; copy verbatim when nothing to translate
const goldRaw = readFileSync(join(keeperDir, "goldens/rules-goldens.json"), "utf8");
const gold = JSON.parse(goldRaw);
if (gold.cases.some((c) => c.slug.includes("@"))) {
  for (const c of gold.cases) if (c.slug.includes("@")) { const [s, dir] = c.slug.split("@"); c.slug = `${s}-${dir}`; }
  put("scripts/fixtures/keeper-goldens.json", JSON.stringify(gold, null, 2) + "\n");
} else {
  put("scripts/fixtures/keeper-goldens.json", goldRaw);
}

console.log(`Imported ${index.length} waters, ${nextRegId - excluded} regulations (${excluded} excluded), ${recent.length} stocking events from ${keeperDir} @ ${keeperSha.slice(0, 7)}.`);
